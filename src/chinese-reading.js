export const escapeText = value => String(value ?? '').replace(/[&<>"']/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character]);
const readingPattern = new RegExp(Object.keys(readingHints).sort((left, right) => right.length - left.length).join('|'), 'gu');

export function readingText(value, enabled = true) {
  const text = String(value ?? '');
  if (!enabled) return escapeText(text);
  let previous = 0;
  let html = '';
  for (const match of text.matchAll(readingPattern)) {
    html += escapeText(text.slice(previous, match.index));
    html += `<ruby>${escapeText(match[0])}<rp>（</rp><rt>${escapeText(readingHints[match[0]])}</rt><rp>）</rp></ruby>`;
    previous = match.index + match[0].length;
  }
  return html + escapeText(text.slice(previous));
}
